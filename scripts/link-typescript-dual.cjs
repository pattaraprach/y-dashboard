/**
 * TypeScript 7 has no stable JS compiler API yet (lands in 7.1).
 * Microsoft's dual install:
 *   - `typescript` -> @typescript/typescript6 (API for eslint / ts-node)
 *   - `@typescript/native` -> typescript@7 (fast native `tsc`)
 *
 * Next.js 16.3 typechecks via the package-local `typescript/bin/tsc` path.
 * typescript6 only ships `tsc6`, so this postinstall exposes TS7 as `tsc`
 * on the typescript package for Next + `npm run typecheck`.
 *
 * @see https://devblogs.microsoft.com/typescript/announcing-typescript-7-0/#running-side-by-side-with-typescript-6.0
 * @see https://nextjs.org/docs/app/api-reference/config/typescript#using-typescript-7
 */
const fs = require('node:fs')
const path = require('node:path')

const root = path.join(__dirname, '..')
const typescriptDir = path.join(root, 'node_modules', 'typescript')
const nativeDir = path.join(root, 'node_modules', '@typescript', 'native')
const pkgPath = path.join(typescriptDir, 'package.json')
const nativeTscJs = path.join(nativeDir, 'lib', 'tsc.js')

if (!fs.existsSync(pkgPath) || !fs.existsSync(nativeTscJs)) {
  process.exit(0)
}

const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'))
const isCompatPackage =
  pkg.name === '@typescript/typescript6' ||
  (pkg.bin && pkg.bin.tsc6 && !pkg.bin.tsc)

if (!isCompatPackage) {
  process.exit(0)
}

const binDir = path.join(typescriptDir, 'bin')
fs.mkdirSync(binDir, { recursive: true })

const wrapperPath = path.join(binDir, 'tsc')
const relativeNativeTsc = path
  .relative(binDir, nativeTscJs)
  .split(path.sep)
  .join('/')

const wrapper = `#!/usr/bin/env node
// Generated by scripts/link-typescript-dual.cjs — runs TypeScript 7 CLI
const result = require('node:child_process').spawnSync(
  process.execPath,
  [require('node:path').join(__dirname, ${JSON.stringify(relativeNativeTsc)}), ...process.argv.slice(2)],
  { stdio: 'inherit' }
)
process.exit(result.status === null ? 1 : result.status)
`

fs.writeFileSync(wrapperPath, wrapper, { mode: 0o755 })

pkg.bin = { ...(pkg.bin || {}), tsc: './bin/tsc' }
fs.writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`)

// Prefer TS7 on the PATH for `npx tsc` / npm scripts
const binLink = path.join(root, 'node_modules', '.bin', 'tsc')
try {
  fs.rmSync(binLink, { force: true })
  fs.symlinkSync(path.join('..', 'typescript', 'bin', 'tsc'), binLink)
} catch {
  // Windows or existing non-symlink — ignore; Next resolves package path directly
}

console.log('linked TypeScript 7 CLI onto typescript package for Next.js dual install')
